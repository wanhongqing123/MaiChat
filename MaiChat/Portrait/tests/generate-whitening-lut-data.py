#!/usr/bin/env python3
"""Losslessly embed the four pinned GPUPixel RGB LUTs; Pillow is generation-only.

Usage: generate-whitening-lut-data.py UPSTREAM_ROOT OUTPUT_INC
Paeth residuals are canonical-Huffman encoded then base64 wrapped. This changes
storage only; decoded dimensions, orientation and every RGB byte remain original.
"""
import base64
from collections import Counter
import hashlib
import heapq
from pathlib import Path
import sys
from PIL import Image

PINNED_PNG_SHA256 = {
    'lookup_gray': '9b7b6da3f0d6102dfd454119c108cc5b56e97176eda4c01871b5dfdcd256952b',
    'lookup_origin': 'b6e8799049eb14482b544861bb444733c22768965f69545893fa8485e85207af',
    'lookup_skin': '5f898a8fe4997b4831c3c7a29fadd4b307f0bb9dc837a7cc5c6d3f2b870b55f5',
    'lookup_light': '5058b32f12f584152c1a5984767415bdeb128e0ea78c858f3529ba596ba06d3a',
}


def paeth(a, b, c):
    p = a + b - c
    da, db, dc = abs(p - a), abs(p - b), abs(p - c)
    return a if da <= db and da <= dc else b if db <= dc else c


def encode(raw, width):
    row = width * 3
    residual = bytes((v - paeth(raw[i - 3] if i % row >= 3 else 0,
                              raw[i - row] if i >= row else 0,
                              raw[i - row - 3] if i >= row and i % row >= 3 else 0)) % 256
                     for i, v in enumerate(raw))
    heap = [(n, s, [s]) for s, n in sorted(Counter(residual).items())]
    heapq.heapify(heap)
    lengths = [0] * 256
    while len(heap) > 1:
        na, sa, aa = heapq.heappop(heap)
        nb, sb, bb = heapq.heappop(heap)
        for s in aa + bb:
            lengths[s] += 1
        heapq.heappush(heap, (na + nb, min(sa, sb), aa + bb))
    if len(heap[0][2]) == 1:
        lengths[heap[0][2][0]] = 1
    code, previous, codes = 0, 0, {}
    for length, s in sorted((n, s) for s, n in enumerate(lengths) if n):
        code <<= length - previous
        codes[s] = (code, length)
        code += 1
        previous = length
    data = bytearray()
    accumulator, bits = 0, 0
    for s in residual:
        c, n = codes[s]
        accumulator = (accumulator << n) | c
        bits += n
        while bits >= 8:
            bits -= 8
            data.append((accumulator >> bits) & 255)
        accumulator &= (1 << bits) - 1
    if bits:
        data.append(accumulator << (8 - bits))
    return lengths, base64.b64encode(data).decode('ascii')


def main():
    upstream, output = map(Path, sys.argv[1:])
    chunks = ['// Generated by tests/generate-whitening-lut-data.py; do not hand-edit.',
              '// GPUPixel ef552bf8ce2d0d41fa9b979bfb5c7cf79374ca88, Apache-2.0.',
              '// Paeth + canonical Huffman + base64 is lossless storage, not a new LUT.']
    for name, symbol in [('lookup_gray', 'Gray'), ('lookup_origin', 'Origin'),
                         ('lookup_skin', 'Skin'), ('lookup_light', 'Light')]:
        path = upstream / 'src' / 'res' / (name + '.png')
        if hashlib.sha256(path.read_bytes()).hexdigest() != PINNED_PNG_SHA256[name]:
            raise ValueError('LUT differs from pinned GPUPixel revision: ' + name)
        image = Image.open(path).convert('RGB')
        raw = image.tobytes()
        lengths, data = encode(raw, image.width)
        chunks += ['', '// ' + name + '.png ' + str(image.size),
                   '// PNG SHA-256: ' + hashlib.sha256(path.read_bytes()).hexdigest(),
                   '// RGB SHA-256: ' + hashlib.sha256(raw).hexdigest(),
                   'static constexpr unsigned char k' + symbol + 'Lengths[256] = {']
        chunks += ['    ' + ', '.join(str(n) for n in lengths[i:i+32]) + ',' for i in range(0, 256, 32)]
        # Keep concatenated literals below MSVC's string size limit as well.
        chunks += ['};', 'static constexpr const char* k' + symbol + 'Data[] = {']
        for start in range(0, len(data), 12288):
            shard = data[start:start+12288]
            chunks += ['    "' + shard[i:i+96] + '"' for i in range(0, len(shard), 96)]
            chunks += ['    ,']
        chunks += ['    nullptr', '};']
        print(name, image.size, 'RGB', len(raw), 'base64', len(data))
    output.write_text('\n'.join(chunks) + '\n')

if __name__ == '__main__':
    main()
